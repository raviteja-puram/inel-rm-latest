import {
  getAllComponents,
  getAllFgProducts,
  getAllProductionPlans,
  getAllProductionRuns,
  getAllStockMovements,
} from './repository.js';
import { buildComponentMetrics } from './calculations.js';
import { getMonthKeyFromDate } from './workingDays.js';

const DEFAULT_SEND_TIME = '17:30';
const pad = (value) => String(value).padStart(2, '0');
const localDateKey = (date = new Date()) => `${date.getFullYear()}-${pad(date.getMonth() + 1)}-${pad(date.getDate())}`;
const fmt = (value) => Number(value || 0).toLocaleString('en-IN');

function escapeHtml(value) {
  return String(value ?? '').replace(/[&<>"']/g, (char) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[char]));
}

function getDailyDigestData(dateKey = localDateKey()) {
  const components = getAllComponents();
  const products = getAllFgProducts();
  const runs = getAllProductionRuns().filter((run) => localDateKey(new Date(run.date)) === dateKey);
  const movements = getAllStockMovements().filter((movement) =>
    ['INWARD', 'BULK_UPDATE'].includes(movement.type) &&
    (movement.receiptDate || localDateKey(new Date(movement.createdAt))) === dateKey,
  );
  const critical = buildComponentMetrics(
    components,
    products,
    getAllProductionRuns(),
    getAllProductionPlans(),
    getMonthKeyFromDate(dateKey),
  ).filter((row) => row.risk === 'critical');
  return { dateKey, runs, movements, critical };
}

function table(headers, rows, emptyText) {
  const head = headers.map((header) => `<th style="padding:8px;text-align:left;border-bottom:1px solid #cbd5e1">${escapeHtml(header)}</th>`).join('');
  const body = rows.length
    ? rows.map((row) => `<tr>${row.map((cell) => `<td style="padding:8px;border-bottom:1px solid #e2e8f0">${escapeHtml(cell)}</td>`).join('')}</tr>`).join('')
    : `<tr><td colspan="${headers.length}" style="padding:16px;color:#64748b">${escapeHtml(emptyText)}</td></tr>`;
  return `<table cellpadding="0" cellspacing="0" style="border-collapse:collapse;width:100%;font-size:12px"><thead style="background:#eff6ff;color:#1e3a8a"><tr>${head}</tr></thead><tbody>${body}</tbody></table>`;
}

